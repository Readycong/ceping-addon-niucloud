CREATE TABLE IF NOT EXISTS `{{prefix}}ceping_record` (
  `id` int unsigned NOT NULL AUTO_INCREMENT COMMENT '主键id',
  `site_id` int unsigned NOT NULL DEFAULT 0 COMMENT '站点id',
  `member_id` int unsigned NOT NULL DEFAULT 0 COMMENT '会员id',
  `test_id` int unsigned NOT NULL DEFAULT 0 COMMENT '选题编号',
  `mode` varchar(20) NOT NULL DEFAULT 'single' COMMENT 'single/partner_inviter/partner_invitee',
  `answers` json NULL COMMENT '作答[{no,optKey}]',
  `score_detail` json NULL COMMENT '计分明细',
  `result_key` varchar(50) NOT NULL DEFAULT '' COMMENT '服务端复核结果key',
  `result_name` varchar(100) NOT NULL DEFAULT '' COMMENT '结果名',
  `total_score` int NOT NULL DEFAULT 0 COMMENT '总分',
  `source` varchar(20) NOT NULL DEFAULT 'home' COMMENT '来源home/category/share/poster/invite',
  `invite_id` int unsigned NOT NULL DEFAULT 0 COMMENT '双人邀请id',
  `partner_record_id` int unsigned NOT NULL DEFAULT 0 COMMENT '配对记录id',
  `status` varchar(20) NOT NULL DEFAULT 'completed' COMMENT 'completed/waiting_partner/paired/canceled',
  `create_time` int NOT NULL DEFAULT 0 COMMENT '完成时间',
  `delete_time` int NOT NULL DEFAULT 0 COMMENT '删除时间',
  PRIMARY KEY (`id`),
  KEY `IDX_ceping_record_member` (`member_id`,`create_time`),
